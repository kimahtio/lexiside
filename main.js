function splitLines(value) {
  return value.replace(/\r\n?/g, "\n").split("\n").map((line) => line.trim()).filter((line) => line.length > 0);
}
function parsePipeList(value) {
  return splitLines(value).map((line) => line.split("|").map((part) => part.trim()));
}
