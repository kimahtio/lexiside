var MAX_LABEL_CHARS = 48;
function escapeLabel(value) {
  return value.replace(/<[^>]*>/g, " ").replace(/[\u0000-\u001F\u007F]/g, " ").replace(/["`\\[\]{}|<>]/g, "").replace(/\s+/g, " ").trim().slice(0, MAX_LABEL_CHARS);
}
function buildWordMapMermaid(model) {
  if (model.relations.length === 0) {
    return null;
  }
  const center = escapeLabel(model.center) || "word";
  const lines = [
    "flowchart TD",
    `  W(["${center}"])`
  ];
  model.relations.forEach((relation, index) => {
    const target = escapeLabel(relation.target) || relation.label;
    const edgeLabel = escapeLabel(relation.label) || "related";
    lines.push(`  W ---|"${edgeLabel}"| n${index + 1}["${target}"]`);
  });
  return lines.join("\n");
}
function isProperNoun(knowledge) {
  return knowledge.identity.partOfSpeech.some(
    (pos) => /proper[-\s]*(?:noun|name)/i.test(pos)
  );
}
function buildWordMapModel(knowledge, maxRelations = 6) {
  if (isProperNoun(knowledge)) {
    return null;
  }
  const relations = selectWordMapRelations(knowledge, maxRelations);
  if (relations.length === 0) {
    return null;
  }
  return {
    center: knowledge.identity.surface,
    relations
  };
}
function wordMapMermaidBlock(model) {
  const mermaid = buildWordMapMermaid(model);
  return mermaid ? ["```mermaid", mermaid, "```"].join("\n") : null;
}

